// EED HALAL — LINE auto-reply server launcher (runs on the owner's machine).
//
// One double-click starts three things and wires them together:
//   1. Internal Business API  (file DB, loopback) — data + owner console
//   2. LINE gateway           (webhook + chat-replier + auto-reply)  :5678
//   3. cloudflared quick tunnel -> public HTTPS URL for LINE's webhook
//
// The public URL is printed at the end. Paste it into LINE Developers as the
// webhook URL. A quick tunnel gives a NEW URL on every start — for a stable
// URL set up a named tunnel (see tools/line/README.md).
//
// Secrets are read from <repo>/.env (never printed). EED_INTERNAL_API_SECRET
// is generated once and appended to .env if missing so the owner console can
// keep the same unlock secret across restarts.
import { spawn } from 'node:child_process';
import { existsSync } from 'node:fs';
import { appendFile, readFile, mkdir } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import {
  BOT_DB_ENV,
  botStorePath,
  compactBotStore,
  openSqlite,
  prepareBotStore,
  pruneOldSessions,
} from './bot-store.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const ENV_PATH = path.join(ROOT, '.env');

const GATEWAY_PORT = 5678;
const API_PORT = 8788;
const DB_DIR = path.join(ROOT, 'data', 'line-runtime');
const RUNTIME_ENV = path.join(DB_DIR, 'runtime.env');
const BOT_DB = path.join(DB_DIR, 'opencode-bot.db');
/** How long a bot conversation stays in the bot's private store. */
const BOT_SESSION_KEEP_DAYS = 7;

/**
 * Prepare the bot's private OpenCode store so customer LINE messages never
 * create sessions in the owner's OpenCode chat list.
 * Returns the env var value for the gateway, or null when the store could not
 * be prepared (the bot then keeps the old shared-store behaviour).
 */
export async function prepareBotRuntime(env = process.env) {
  const target = botStorePath({ ...env, [BOT_DB_ENV]: BOT_DB });
  const prepared = await prepareBotStore({ target });
  if (!prepared.ok) {
    return { ok: false, path: target, reason: prepared.reason };
  }
  if (prepared.created) {
    console.log(`    แยกที่เก็บแชทของบอทไว้ที่ ${target}`);
  }

  // Old bot conversations are pruned so the private store cannot grow forever.
  const db = await openSqlite(target);
  if (db) {
    try {
      const pruned = pruneOldSessions(db, { keepDays: BOT_SESSION_KEEP_DAYS });
      if (pruned.removed) {
        console.log(`    ล้างแชทเก่าของบอท ${pruned.removed} ห้อง (เก็บไว้ ${BOT_SESSION_KEEP_DAYS} วัน)`);
        db.close();
        // Deleting rows does not shrink the file: give the space back.
        await compactBotStore(target);
        return { ok: true, path: target, created: prepared.created };
      }
    } catch {
      // Pruning is housekeeping; never block the launcher for it.
    } finally {
      try { db.close(); } catch { /* already closed */ }
    }
  }
  return { ok: true, path: target, created: prepared.created };
}

const CLOUDFLARED_CANDIDATES = [
  process.env.CLOUDFLARED_PATH,
  'C:\\Program Files (x86)\\cloudflared\\cloudflared.exe',
  'C:\\Program Files\\cloudflared\\cloudflared.exe',
  'cloudflared',
].filter(Boolean);

// Minimal .env parser (the project has no dotenv dependency).
export function parseEnvFile(text) {
  const out = {};
  for (const raw of String(text).split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq <= 0) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

async function loadEnv() {
  // Order: .env (owner config) -> runtime.env (machine-local secrets such as
  // the PostgreSQL password) -> real process env (operator override).
  // data/line-runtime/ is gitignored, so runtime.env never leaves the machine.
  const parsed = {};
  const fromFile = async (file) => {
    if (!existsSync(file)) return {};
    return parseEnvFile(await readFile(file, 'utf8'));
  };
  Object.assign(parsed, await fromFile(ENV_PATH), await fromFile(RUNTIME_ENV));
  // Real process environment wins over any file (operator override).
  return { ...parsed, ...process.env };
}

// Ensure the internal API secret exists and is stable across restarts.
async function ensureApiSecret(env) {
  if (env.EED_INTERNAL_API_SECRET) return env.EED_INTERNAL_API_SECRET;
  const generated = randomUUID();
  const line = `\n# Generated by tools/line/launcher.mjs (internal API unlock secret).\nEED_INTERNAL_API_SECRET=${generated}\n`;
  await appendFile(ENV_PATH, line, 'utf8');
  return generated;
}

function findCloudflared() {
  const found = CLOUDFLARED_CANDIDATES.find((candidate) => existsSync(candidate));
  return found || null;
}

function childEnv(env, extra = {}) {
  const flat = {};
  for (const [key, value] of Object.entries({ ...env, ...extra })) {
    if (value === undefined || value === null) continue;
    flat[key] = String(value);
  }
  return flat;
}

async function waitForApi(timeoutMs = 15000) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    try {
      const response = await fetch(`http://127.0.0.1:${API_PORT}/healthz`, { signal: AbortSignal.timeout(800) });
      if (response.ok) return true;
    } catch { /* not up yet */ }
    await new Promise((resolve) => setTimeout(resolve, 200));
  }
  return false;
}

function runCloudflaredTunnel(cloudflared, env) {
  // Quick tunnel: free, no account, but a new random URL each start.
  const child = spawn(cloudflared, ['tunnel', '--url', `http://127.0.0.1:${GATEWAY_PORT}`, '--no-autoupdate'], {
    cwd: ROOT,
    env: childEnv(env),
    stdio: ['ignore', 'pipe', 'pipe'],
    windowsHide: true,
  });
  let url = null;
  const onData = (chunk) => {
    const text = String(chunk);
    const match = text.match(/https:\/\/[a-z0-9-]+\.trycloudflare\.com/i);
    if (match && !url) url = match[0];
    process.stdout.write(text);
  };
  child.stdout.on('data', onData);
  child.stderr.on('data', onData);
  child.on('error', (error) => process.stderr.write(`cloudflared ไม่สำเร็จ: ${error.message}\n`));
  return { child, getUrl: () => url };
}

/** Open the owner console in the default browser once the API is up.
 *  Best effort only: a headless machine (or a locked desktop) simply keeps the
 *  printed URL. Set EED_OPEN_CONSOLE=0 to never open it. */
function openOwnerConsole(env = process.env) {
  const url = `http://127.0.0.1:${API_PORT}/owner/`;
  console.log(`  หน้าจอเจ้าของ: ${url}`);
  if (String(env.EED_OPEN_CONSOLE || '1').trim() === '0') {
    console.log('  (เปิดเองไม่ได้ตามที่ตั้งไว้ — เปิดลิงก์เองได้จากที่อยู่ข้างบน)\n');
    return;
  }
  const opener = process.platform === 'win32' ? { cmd: 'cmd', args: ['/c', 'start', '', url] }
    : process.platform === 'darwin' ? { cmd: 'open', args: [url] }
      : { cmd: 'xdg-open', args: [url] };
  try {
    const child = spawn(opener.cmd, opener.args, { stdio: 'ignore', windowsHide: true, detached: true });
    child.on('error', () => {});
    child.unref();
  } catch {
    // Never let a cosmetic convenience stop the server from coming up.
  }
}

async function main() {
  await mkdir(DB_DIR, { recursive: true });
  const env = await loadEnv();
  const apiSecret = await ensureApiSecret(env);

  if (!env.LINE_CHANNEL_SECRET) {
    process.stderr.write('ยังไม่ได้ตั้ง LINE_CHANNEL_SECRET ใน .env — ใส่ก่อนแล้วเปิดใหม่\n');
    process.exitCode = 1;
    return;
  }

  console.log('=== EED HALAL LINE server (เครื่องเจ้าของ) ===\n');

  // 1. Internal API (PostgreSQL when a connection is configured, else the
  // file DB) — drafts/customers survive a restart either way.
  const usePostgres = Boolean(env.DATABASE_URL);
  console.log(`[1/3] เริ่ม Internal API (${usePostgres ? 'PostgreSQL' : 'file DB'}) ที่ 127.0.0.1:${API_PORT} …`);
  const api = spawn(process.execPath, [path.join(ROOT, 'server', 'internal-api.mjs')], {
    cwd: ROOT,
    env: childEnv(env, {
      EED_INTERNAL_API_SECRET: apiSecret,
      DB_ADAPTER: usePostgres ? 'postgres' : 'file',
      DB_DIR,
      INTERNAL_API_PORT: String(API_PORT),
    }),
    stdio: 'inherit',
  });

  if (!(await waitForApi())) {
    process.stderr.write('Internal API ไม่พร้อม — ตรวจ log ด้านบน\n');
    api.kill();
    process.exitCode = 1;
    return;
  }
  console.log('    พร้อม ✓\n');

  // The console is the owner's only window into the queue, so open it here
  // instead of making them find the address in the log.
  openOwnerConsole(env);

  // 2. LINE gateway.
  console.log(`[2/3] เริ่ม LINE gateway ที่ 127.0.0.1:${GATEWAY_PORT} …`);
  // The bot writes its OpenCode sessions into its own private store, so
  // customer messages never show up in the owner's OpenCode chat list.
  const botRuntime = await prepareBotRuntime(env);
  if (!botRuntime.ok) {
    console.log(`    ⚠ แยกที่เก็บแชทของบอทไม่สำเร็จ (${botRuntime.reason}) — บอทจะใช้ที่เก็บแชทร่วมกับเจ้าของ`);
  }
  const gateway = spawn(process.execPath, [path.join(ROOT, 'server', 'line-gateway.mjs')], {
    cwd: ROOT,
    env: childEnv(env, {
      EED_INTERNAL_API_SECRET: apiSecret,
      INTERNAL_API_PORT: String(API_PORT),
      LINE_WEBHOOK_PORT: String(GATEWAY_PORT),
      ...(botRuntime.ok ? { [BOT_DB_ENV]: botRuntime.path } : {}),
    }),
    stdio: 'inherit',
  });
  console.log(`    พร้อม ✓ (โหมดเงา — ไม่มีการส่งอัตโนมัติ ทุกข้อความรอเจ้าของกดส่ง)\n`);

  // 3. cloudflared tunnel.
  const cloudflared = findCloudflared();
  if (!cloudflared) {
    console.log('[3/3] ไม่พบ cloudflared — ข้าม tunnel (LINE ยิง webhook ไม่ได้จนกว่าจะติดตั้ง)\n');
    console.log('ติดตั้งจาก https://developers.cloudflare.com/cloudflared/ หรือใช้ ngrok แทน\n');
  } else {
    console.log('[3/3] เปิด cloudflared quick tunnel …');
    const tunnel = runCloudflaredTunnel(cloudflared, env);
    await new Promise((resolve) => setTimeout(resolve, 4000));
    if (tunnel.getUrl()) {
      console.log('\n==============================================');
      console.log(`  Webhook URL:  ${tunnel.getUrl()}/`);
      console.log('  เอา URL นี้ไปวางที่ LINE Developers > Messaging API > Webhook URL');
      console.log('  หมายเหตุ: quick tunnel เปลี่ยน URL ทุกครั้งที่เปิดใหม่');
      console.log('==============================================\n');
    } else {
      console.log('  (รอ URL จาก cloudflared ดู log ด้านบน — ขึ้นบรรทัด trycloudflare.com)\n');
    }
  }

  if (!env.LINE_CHANNEL_ACCESS_TOKEN) {
    console.log('⚠ ยังไม่ได้ตั้ง LINE_CHANNEL_ACCESS_TOKEN ใน .env');
    console.log('  → รับข้อความได้ แต่ส่งตอบไม่ได้ (fail closed)');
    console.log('  → ไปเอา token จาก LINE Developers > Messaging API > Channel access token ใส่ใน .env\n');
  }

  console.log('ปิดหน้าต่างนี้ = หยุดทั้งระบบ (API + gateway + tunnel)\n');

  const shutdown = () => {
    for (const child of [api, gateway]) {
      try { child.kill(); } catch { /* already gone */ }
    }
  };
  process.on('SIGINT', shutdown);
  process.on('SIGTERM', shutdown);
  await new Promise((resolve) => {
    gateway.once('exit', () => { shutdown(); resolve(); });
    api.once('exit', () => { shutdown(); resolve(); });
  });
}

// Running the module must not start the whole stack: only the CLI does.
const isCli = process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (isCli) {
  main().catch((error) => {
    process.stderr.write(`launcher ไม่สำเร็จ: ${error.message}\n`);
    process.exitCode = 1;
  });
}